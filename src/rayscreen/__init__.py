"""Screens and widgets on top of raygui: windows like the main game screen or the options screen.

A screen is a tree of specs (widgets in containers). `layout` gives every node its rect without
raylib; `draw.frame` walks the laid-out tree each frame, calls the matching raygui control, and
returns the events no screen consumed. The `ScreenManager` stack navigates between screens; a
`Window` is a modal panel inside a screen. A screen's `hover` and `menu` hooks give the tooltip and
the context menu for what lies under the mouse on it (the game's world). A picture with `drag` is
dragged onto another with `drop`, or off every window onto the screen: its event's value is a `Drop`.
"""

